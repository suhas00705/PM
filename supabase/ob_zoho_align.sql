insert into public.st_fx_backup (id, price, list_price, doc_total, line_total, tax_calc, freight_charges, doc_total_fc, rate)
  select s.id, s.price, s.list_price, s.doc_total, s.line_total, s.tax_calc, s.freight_charges, s.doc_total_fc, 1 / f.exchange_rate
  from public.sales_lines s join public.st_fix_fx f on f.oa = s.doc_num::text
  where s.doc_type = 'OB' and s.source = 'excel'
    and s.id not in (select id from public.st_fx_backup)
    and s.id not in (select id from public.sales_lines_fx_adj);
update public.sales_lines s
   set price = b.price * b.rate, list_price = b.list_price * b.rate, doc_total = b.doc_total * b.rate,
       line_total = b.line_total * b.rate, tax_calc = b.tax_calc * b.rate, freight_charges = b.freight_charges * b.rate,
       doc_total_fc = b.doc_total_fc * b.rate
  from public.st_fx_backup b
 where b.id = s.id and s.doc_total_fc is not distinct from b.doc_total_fc;   -- only once

